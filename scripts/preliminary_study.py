#!/usr/bin/env python
"""Preliminary study (Section 3, Figure 2): teacher entropy versus cross-view variation.

A frozen teacher scores prefixes generated by a fixed student checkpoint under two
instruction wrappers of the same task. For every sampled response position the first-view
entropy and the cross-view Jensen-Shannon divergence (Equation 1) are recorded; pairs are
then partitioned into first-view entropy quartiles.

    python scripts/preliminary_study.py --toy --num-pairs 2000 --output results/prelim.json
    python scripts/preliminary_study.py --config configs/qwen3_1p7b/vdopd.yaml --num-pairs 5000

``--toy`` uses the synthetic toy pair of the quick start (not the paper's models).
"""

from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path

import numpy as np

from vdopd.config import load_config
from vdopd.data.problems import build_messages
from vdopd.diagnostics import entropy_quartile_summary, paired_view_statistics
from vdopd.pipeline import diagnostic_setting_from_config, toy_diagnostic_setting
from vdopd.seeding import derive_rng, derive_seed
from vdopd.views import TRAIN_WRAPPERS, apply_wrapper


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--config", help="YAML experiment file (real models)")
    source.add_argument("--toy", action="store_true", help="synthetic toy pair (CPU)")
    parser.add_argument("--set", dest="overrides", action="append", default=[])
    parser.add_argument("--student", default=None, help="student checkpoint (default: initial)")
    parser.add_argument("--num-pairs", type=int, default=5000)
    parser.add_argument("--num-prompts", type=int, default=128)
    parser.add_argument("--seed", type=int, default=11)
    parser.add_argument("--output", default=None)
    parser.add_argument("--plot", default=None, help="write Figure 2 to this image file")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s: %(message)s")

    if args.toy:
        setting = toy_diagnostic_setting(args.seed)
    else:
        setting = diagnostic_setting_from_config(
            load_config(args.config, args.overrides), args.student
        )
    problems = setting.update_problems[: args.num_prompts]
    messages = [
        build_messages(
            p.question,
            setting.prompt_template,
            setting.decoding.system_prompt,
            setting.decoding.exemplars,
        )
        for p in problems
    ]
    student_prompts = [setting.codec.encode(m) for m in messages]
    # The two instruction wrappers of Table 5 define the paired teacher views.
    view_a = [setting.codec.encode(apply_wrapper(m, TRAIN_WRAPPERS[0])) for m in messages]
    view_b = [setting.codec.encode(apply_wrapper(m, TRAIN_WRAPPERS[1])) for m in messages]

    responses: list[list[int]] = []
    size = setting.rollout.generation_batch_size
    for chunk, start in enumerate(range(0, len(student_prompts), size)):
        responses.extend(
            setting.student.generate(
                student_prompts[start : start + size],
                max_new_tokens=setting.rollout.max_response_tokens,
                temperature=setting.rollout.temperature,
                top_p=setting.rollout.top_p,
                top_k=setting.rollout.top_k,
                seed=derive_seed(args.seed, "rollout", 0, chunk),
            )
        )
    statistics = paired_view_statistics(
        setting.teacher,
        view_a,
        view_b,
        responses,
        block_size=setting.train.position_block_size,
        microbatch_size=setting.train.microbatch_size,
    )
    entropy = statistics["entropy_p1"].numpy()
    js = statistics["js_divergence"].numpy()
    if len(entropy) > args.num_pairs:
        keep = derive_rng(args.seed, "evaluation").choice(len(entropy), args.num_pairs, False)
        entropy, js = entropy[keep], js[keep]

    summary = entropy_quartile_summary(entropy, js)
    print(f"paired predictions: {len(entropy)}")
    print("quartile  entropy range (nats)   JS p5    median   p95")
    for row in summary:
        print(
            f"Q{row['quartile']}        {row['entropy_min']:.3f} - {row['entropy_max']:.3f}"
            f"          {row['js_p5']:.3f}    {row['js_median']:.3f}    {row['js_p95']:.3f}"
        )
    correlation = float(np.corrcoef(entropy, js)[0, 1]) if len(entropy) > 1 else float("nan")
    print(f"Pearson correlation between first-view entropy and JS divergence: {correlation:.3f}")

    if args.output:
        Path(args.output).parent.mkdir(parents=True, exist_ok=True)
        with open(args.output, "w", encoding="utf-8") as handle:
            json.dump(
                {
                    "num_pairs": len(entropy),
                    "quartiles": summary,
                    "pearson": correlation,
                    "entropy": entropy.tolist(),
                    "js_divergence": js.tolist(),
                },
                handle,
            )
    if args.plot:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        figure, (left, right) = plt.subplots(1, 2, figsize=(9, 3.2))
        hexbin = left.hexbin(js, entropy, gridsize=40, cmap="Blues", mincnt=1)
        figure.colorbar(hexbin, ax=left, label="Pairs per hexagon")
        left.set_xlabel("Cross-view variation ($D_{JS}$, nats)")
        left.set_ylabel("First-view entropy (nats)")
        left.set_title("(a) Entropy and view variation")
        order = np.argsort(entropy, kind="stable")
        right.boxplot(
            [js[group] for group in np.array_split(order, 4)], whis=(5, 95), showfliers=True
        )
        right.set_xticklabels(["Q1", "Q2", "Q3", "Q4"])
        right.set_xlabel("Entropy quartile (low to high)")
        right.set_ylabel("Cross-view variation ($D_{JS}$, nats)")
        right.set_title("(b) Variation by entropy quartile")
        figure.tight_layout()
        figure.savefig(args.plot, dpi=200)


if __name__ == "__main__":
    main()
